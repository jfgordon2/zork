#!/usr/bin/env python3
"""Compile the authorized PRIZM hint guides into the cartridge's topic tree."""

import json
import pathlib
import re
import sys
from html.parser import HTMLParser


class HintText(HTMLParser):
    """Convert PRIZM's HTML fragments to lines the GBA font can display."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.parts = []

    def handle_starttag(self, tag, attrs):
        if tag in ("p", "div", "pre", "br", "li"):
            self.parts.append("\n")
        if tag == "li":
            self.parts.append("- ")

    def handle_endtag(self, tag):
        if tag in ("p", "div", "pre", "li"):
            self.parts.append("\n")

    def handle_data(self, data):
        self.parts.append(data)


def plain_text(value):
    parser = HintText()
    parser.feed(value.replace("\r\n", "\n").replace("\r", "\n"))
    parser.close()
    lines = (re.sub(r"[ \t]+", " ", line).strip() for line in "".join(parser.parts).split("\n"))
    return "\n".join(line for line in lines if line)


def c_string(value):
    return json.dumps(value.replace("\r\n", "\n").replace("\r", "\n"), ensure_ascii=True).replace("?", "\\?")


def emit_guide(path, prefix, output):
    root = json.loads(path.read_text(encoding="utf-8"))
    # The website presents the two shared About and Credits pages separately.
    root["children"] = root["children"][2:]
    nodes = [None]

    def add(node, index, title, parent):
        kind = node["type"]
        if kind == "menu":
            children = node["children"]
            first = len(nodes)
            nodes.extend([None] * len(children))
            for offset, child in enumerate(children):
                add(child["child"], first + offset, child["title"], index)
            nodes[index] = (title, parent, first, len(children), "NULL")
        elif kind in ("hints", "items", "page"):
            clues = node["hints"] if kind == "hints" else [node["content"]]
            if not clues or not all(isinstance(clue, str) and clue.strip() for clue in clues):
                raise ValueError(f"Invalid hint content in {path}: {title}")
            name = f"{prefix}_clues_{index}"
            output.append(f"static const char *const {name}[] = {{")
            output.extend(f"    {c_string(plain_text(clue))}," for clue in clues)
            output.append("};")
            nodes[index] = (title, parent, 0, len(clues), name)
        else:
            raise ValueError(f"Unknown hint node type in {path}: {kind}")

    add(root, 0, "InvisiClues", 0)
    output.append(f"static const HintEntry {prefix}[] = {{")
    for title, parent, first, count, clues in nodes:
        output.append(f"    {{{c_string(title)}, {clues}, {parent}, {first}, {count}}},")
    output.append("};")
    return [(index, title) for index, (title, _, _, _, clues) in enumerate(nodes) if clues != "NULL"]


def emit_context(path, guides, output):
    output.append("static const ContextHint contextual_hints[] = {")
    seen = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        chapter, rooms, target, label, question = line.split("\t")
        chapter, target = int(chapter) - 1, int(target)
        if not 0 <= chapter < len(guides) or not 0 <= target <= 0xFFFF or not label:
            raise ValueError(f"Invalid context mapping: {line}")
        matches = [index for index, title in guides[chapter] if title == question]
        if len(matches) != 1:
            raise ValueError(f"Context must identify one guide entry: {question}")
        for room in map(int, rooms.split(",")):
            key = chapter, room, matches[0]
            if not 1 <= room <= 255 or key in seen:
                raise ValueError(f"Invalid or repeated context: {line}")
            seen.add(key)
            output.append(f"    {{{chapter}, {room}, {target}, {matches[0]}, {c_string(label)}}},")
    output.append("};")


def main():
    destination, context, *inputs = map(pathlib.Path, sys.argv[1:])
    if len(inputs) != 3:
        raise SystemExit("Usage: invisiclues.py OUTPUT CONTEXT_TSV ZORK1_JSON ZORK2_JSON ZORK3_JSON")
    output = ["/* Generated by tools/invisiclues.py from stories/hints. */"]
    guides = [emit_guide(path, f"invisiclues_{chapter}", output) for chapter, path in enumerate(inputs, 1)]
    output.append("static const HintEntry *const invisiclues[] = {invisiclues_1, invisiclues_2, invisiclues_3};")
    emit_context(context, guides, output)
    destination.write_text("\n".join(output) + "\n", encoding="ascii")


if __name__ == "__main__":
    main()
