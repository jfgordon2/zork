import json
from pathlib import Path
import sys

from PIL import Image


ALPHA_CUTOFF = 112


def make_pose(name, image):
    alpha = image.getchannel("A").point(lambda value: 255 if value >= ALPHA_CUTOFF else 0)
    bounds = alpha.getbbox()
    if bounds is None:
        raise ValueError(f"{name} is empty")
    image = image.crop(bounds)
    rows = []
    for y in range(image.height):
        pixels = image.crop((0, y, image.width, y + 1)).getdata()
        colors = [
            0x8000 | (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)
            if a >= ALPHA_CUTOFF else 0
            for r, g, b, a in pixels
        ]
        rows.append("    " + ", ".join(f"0x{color:04x}" for color in colors) + ",")
    return "\n".join([
        f"static const Color {name}Pixels[] = {{",
        *rows,
        "};",
        f"static const SceneSprite {name} = "
        f"{{{image.width}, {image.height}, {name}Pixels}};",
    ])


def compile_art(manifest, output):
    poses = []
    frames = json.loads(manifest.read_text())
    for key, sprite in frames.items():
        with Image.open(manifest.with_name(f"{key}.png")) as sheet:
            for index, cell in enumerate(sprite["cells"]):
                # Derived sprites have fixed names, so build them from the first pose only;
                # a second pose would otherwise emit duplicate C symbols.
                first = index == 0
                x, y, w, h = (cell[name] for name in ("x", "y", "width", "height"))
                if x < 0 or y < 0 or w < 1 or h < 1 or x + w > sheet.width or y + h > sheet.height:
                    raise ValueError(f"{key} {cell['pose']} falls outside the sheet")
                pose = sheet.crop((x, y, x + w, y + h)).convert("RGBA")
                name = "Art" + "".join(part.capitalize() for part in key.split("_")) + cell["pose"]
                if first and key in ("teapot", "newspaper", "matchbook", "place_mat", "letter_opener"):
                    # The new gazebo table is in the middle distance; ground drops retain full scale.
                    table = pose.resize((max(1, pose.width // 2), max(1, pose.height // 2)), Image.Resampling.LANCZOS)
                    table_name = "Art" + "".join(part.capitalize() for part in key.split("_")) + "Table"
                    poses.append(make_pose(table_name, table))
                if first and key == "letter_opener":
                    inserted = pose.resize((12, 4), Image.Resampling.LANCZOS)
                    poses.append(make_pose("ArtLetterOpenerInserted", inserted))
                if first and key == "collar":
                    worn = pose.resize((52, 13), Image.Resampling.LANCZOS)
                    poses.append(make_pose("ArtCollarWorn", worn))
                if first and key == "crown":
                    poses.append(make_pose("ArtCrownSafe", pose.resize((16, 11), Image.Resampling.LANCZOS)))
                if first and key == "pile_bodies":
                    # The same remains appear through the Hades gate at a
                    # distance and larger in the Land of the Dead.
                    poses.append(make_pose(
                        "ArtPileBodiesDistant",
                        pose.resize((28, 13), Image.Resampling.LANCZOS),
                    ))
                if key == "leaflet" and cell["pose"] == "Folded":
                    poses.append(make_pose("ArtCardSafe", pose.resize((8, 5), Image.Resampling.LANCZOS)))
                if key in ("lizard_head_awake", "lizard_head_asleep") and cell["pose"] == "Embedded":
                    # The door recedes into the Workshop when opened from the Guarded Room.
                    edge = pose.resize((12, 14), Image.Resampling.LANCZOS)
                    poses.append(make_pose(name.replace("Embedded", "Open"), edge))
                if first and key == "unicorn":
                    garden = pose.resize((47, 35), Image.Resampling.LANCZOS)
                    poses.append(make_pose("ArtUnicornGarden", garden))
                if key in ("banker", "volcano_gnome"):
                    pose = pose.resize((34, 35), Image.Resampling.LANCZOS)
                if key == "cerberus":
                    pose = pose.resize((91, 56), Image.Resampling.LANCZOS)
                if key == "sailor":
                    # The ship is still offshore when the sailor is visible.
                    pose = pose.resize((11, 12), Image.Resampling.LANCZOS)
                poses.append(make_pose(name, pose))
    output.write_text("\n\n".join(["/* Generated by tools/encounters.py. */", *poses]) + "\n")


if __name__ == "__main__":
    compile_art(*map(Path, sys.argv[1:]))
